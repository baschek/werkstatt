export type IconName = keyof typeof BITMAPS

export function PixelIcon({ name, size = 12, style, title }: { name: IconName; size?: number; style?: CSSProperties; title?: string }) {
  const rows = BITMAPS[name] as readonly string[]
  const w = Math.max(...rows.map((r) => r.length))
  const h = rows.length
  const rects: string[] = []
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] === '#') {
        let e = x
        while (e < row.length && row[e] === '#') e++
        rects.push(`M${x} ${y}h${e - x}v1h-${e - x}z`)
        x = e
      } else x++
    }
  })
  return (
    <svg className="px-icon" width={(size * w) / Math.max(w, h)} height={(size * h) / Math.max(w, h)} viewBox={`0 0 ${w} ${h}`} shapeRendering="crispEdges"
      fill="currentColor" role={title ? 'img' : undefined} aria-label={title} aria-hidden={title ? undefined : true} style={style}>
      <path d={rects.join('')} />
    </svg>
  )
}

